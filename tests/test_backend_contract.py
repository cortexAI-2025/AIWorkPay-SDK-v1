"""The SDK against the JSON the backend really produces.

``tests/contract_fixtures`` is a copy of ``contract/fixtures`` of Aiworkpay-v2, generated by running the backend's own
code and drift-checked there. A changed response shape on the backend fails there first, then here once the copy is
refreshed. ``MANIFEST.json`` carries a SHA-256 per file: a hand-edited copy is detected.
"""

from __future__ import annotations

import hashlib
import json
from decimal import Decimal
from pathlib import Path
from typing import Any

import pytest

from aiworkpay import MissionStatus, construct_event, sign
from aiworkpay.errors import RateLimitError, error_from_response
from aiworkpay.models import Account, Mission, Transaction

DIR = Path(__file__).parent / "contract_fixtures"


def fixture(name: str) -> Any:
    return json.loads((DIR / f"{name}.json").read_text(encoding="utf-8"))


def test_the_copied_fixtures_are_the_ones_the_backend_published() -> None:
    manifest = fixture("MANIFEST")
    files = sorted(p.name for p in DIR.glob("*.json") if p.name != "MANIFEST.json")
    assert files == sorted(manifest)
    for name in files:
        assert hashlib.sha256((DIR / name).read_bytes()).hexdigest() == manifest[name]


def test_a_mission_read_by_its_agent() -> None:
    late = Mission.from_api(fixture("mission.agent.in_progress_overdue"))
    assert late.status == MissionStatus.IN_PROGRESS
    assert late.budget == Decimal("25")  # the API sends a Decimal as a string
    assert late.overdue is True
    assert late.deadline is not None and late.deadline.tzinfo is not None
    assert [a.kind for a in late.attachments] == ["BRIEF"], "proofs are hidden until delivery"
    assert late.proofs == ()

    delivered = Mission.from_api(fixture("mission.agent.delivered"))
    assert delivered.result_available and not delivered.overdue
    assert delivered.result_note == "Fait : 20 fiches corrigées."
    assert delivered.result_data == {"corrected": 20}
    assert [(p.kind, p.source, p.scan_status) for p in delivered.proofs] == [("PROOF", "upload", "CLEAN")]


def test_an_older_server_without_the_overdue_flag_reads_as_not_overdue() -> None:
    data = fixture("mission.agent.in_progress_overdue")
    del data["overdue"]
    assert Mission.from_api(data).overdue is False


def test_the_account() -> None:
    account = Account.from_api(fixture("account"))
    assert account.usage.remaining_this_month == Decimal("475")
    assert account.max_next_mission_budget == Decimal("100")
    assert account.usage.net_paid == Decimal("25")
    assert account.missions_by_status == {"IN_PROGRESS": 1}


def test_the_ledger() -> None:
    page = fixture("transactions")
    rows = [Transaction.from_api(t) for t in page["transactions"]]
    assert page["total"] == len(rows) == 1
    assert rows[0].amount == Decimal("25") and rows[0].refunded is False
    assert rows[0].mission_status == MissionStatus.IN_PROGRESS


def test_the_error_envelope() -> None:
    limited = fixture("error.rate_limited")
    error = error_from_response(limited["status"], limited["body"], request_id="req", retry_after=12.0)
    assert isinstance(error, RateLimitError)
    assert error.code == "RATE_LIMITED" and error.details == {"retryAfterSeconds": 12}
    missing = fixture("error.not_found")
    assert (
        error_from_response(missing["status"], missing["body"], request_id="req", retry_after=None).code
        == "MISSION_NOT_FOUND"
    )


@pytest.mark.parametrize(
    ("name", "event_type", "status"),
    [
        ("webhook.mission.assigned", "mission.assigned", MissionStatus.ASSIGNED),
        ("webhook.mission.delivered", "mission.delivered", MissionStatus.DELIVERED),
        ("webhook.mission.canceled", "mission.canceled", MissionStatus.CANCELED),
    ],
)
def test_a_signed_webhook_event_is_verified_and_decoded(name: str, event_type: str, status: MissionStatus) -> None:
    body = (DIR / f"{name}.json").read_text(encoding="utf-8")
    created = fixture(name)["created"]
    header = sign("awhsec_contract", body, created)
    event = construct_event(body, header, "awhsec_contract", tolerance=None)
    assert event.type == event_type
    mission = event.mission
    assert mission is not None and mission.status == status
    assert mission.budget == Decimal("25"), (
        "webhook amounts are numbers, REST amounts are strings: both read as Decimal"
    )


def test_the_cancellation_reason_is_exposed() -> None:
    body = (DIR / "webhook.mission.canceled.json").read_text(encoding="utf-8")
    event = construct_event(body, sign("s", body, 1792400000), "s", tolerance=None)
    assert event.reason == "expired"


def test_the_delivered_event_carries_the_result() -> None:
    body = (DIR / "webhook.mission.delivered.json").read_text(encoding="utf-8")
    mission = construct_event(body, sign("s", body, 1792400000), "s", tolerance=None).mission
    assert mission is not None
    assert mission.result_note == "Fait : 20 fiches corrigées." and mission.result_data == {"corrected": 20}
